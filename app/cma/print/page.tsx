"use client";

import { useEffect, useState, useRef } from "react";
import dynamic from "next/dynamic";
import { CMAReportData, RENOVATION_OPTIONS } from "@/lib/cma";
import CmaReport from "@/components/CmaReport";
import CmaAiAnalysis from "@/components/CmaAiAnalysis";
import RenovationAdjustments from "@/components/RenovationAdjustments";

const CmaMap = dynamic(() => import("@/components/CmaMap"), { ssr: false });
const CmaCharts = dynamic(() => import("@/components/CmaCharts"), { ssr: false });

interface PrintData {
  reportData: CMAReportData;
  aiAnalysis: string | null;
  renovationData: {
    renovations: Record<string, number>;
    adjustedValue: number;
    addedValue: number;
    totalSpent: number;
  } | null;
}

const fmt = (n: number) =>
  new Intl.NumberFormat("en-US", { style: "currency", currency: "USD", maximumFractionDigits: 0 }).format(n);

export default function PrintPage() {
  const [printData, setPrintData] = useState<PrintData | null>(null);
  const [ready, setReady] = useState(false);
  const printTriggered = useRef(false);

  useEffect(() => {
    const raw = sessionStorage.getItem("cma_print_data");
    if (raw) {
      try {
        const data = JSON.parse(raw) as PrintData;
        setPrintData(data);
      } catch { /* invalid */ }
    }
  }, []);

  useEffect(() => {
    if (printData && !printTriggered.current) {
      const timer = setTimeout(() => {
        setReady(true);
        const printTimer = setTimeout(() => {
          window.print();
          printTriggered.current = true;
        }, 1500);
        return () => clearTimeout(printTimer);
      }, 800);
      return () => clearTimeout(timer);
    }
  }, [printData]);

  if (!printData) {
    return (
      <div className="flex items-center justify-center min-h-screen">
        <p className="text-muted-foreground">Loading report data...</p>
      </div>
    );
  }

  const { reportData, aiAnalysis, renovationData } = printData;

  const selectedRenovations = renovationData?.renovations
    ? Object.entries(renovationData.renovations)
        .filter(([, amount]) => amount > 0)
        .map(([key, amount]) => {
          const opt = RENOVATION_OPTIONS.find((o) => o.key === key);
          const roi = opt?.roiPercent ?? 0;
          const added = amount * (roi / 100);
          return { key, label: opt?.label ?? key, roi, amount, added };
        })
    : [];

  return (
    <div className="p-6 max-w-[900px] mx-auto bg-white print:p-0 print:max-w-none">
      <div className="hidden print:block mb-6 border-b pb-4">
        <h1 className="text-2xl font-bold">CMA Report</h1>
        <p className="text-sm text-gray-500">
          Comparative Market Analysis — Generated by Domuzz
        </p>
        <p className="text-xs text-gray-400 mt-1">
          Report for: {reportData.subjectProperty.address} —{" "}
          {new Date().toLocaleDateString()}
        </p>
      </div>

      {ready && (
        <>
          <CmaReport reportData={reportData} />
          <CmaMap reportData={reportData} />
          <CmaCharts reportData={reportData} />

          {aiAnalysis && (
            <div className="mt-6 border border-blue-200 rounded-lg p-4 bg-blue-50/50 print:break-inside-avoid">
              <h3 className="text-sm font-semibold mb-3">AI Market Analysis</h3>
              <div className="space-y-2">
                {aiAnalysis.split(/\n\s*\n/).map((p, i) => (
                  <p key={i} className="text-sm text-gray-600 leading-relaxed">
                    {p.replace(/\s+/g, " ").trim()}
                  </p>
                ))}
              </div>
            </div>
          )}

          {renovationData && selectedRenovations.length > 0 && (
            <div className="mt-6 border border-green-200 rounded-lg p-4 bg-green-50/50 print:break-inside-avoid">
              <h3 className="text-sm font-semibold mb-3">🏠 Renovation Value Adjustments</h3>
              <table className="w-full text-sm mb-3">
                <thead>
                  <tr className="text-xs text-gray-500 border-b">
                    <th className="text-left py-1 font-medium">Renovation</th>
                    <th className="text-right py-1 font-medium">ROI</th>
                    <th className="text-right py-1 font-medium">Amount Spent</th>
                    <th className="text-right py-1 font-medium">Added Value</th>
                  </tr>
                </thead>
                <tbody>
                  {selectedRenovations.map((r) => (
                    <tr key={r.key} className="border-b border-gray-100">
                      <td className="py-1.5">{r.label}</td>
                      <td className="text-right py-1.5">~{r.roi}%</td>
                      <td className="text-right py-1.5">{fmt(r.amount)}</td>
                      <td className="text-right py-1.5 text-green-600">+{fmt(r.added)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
              <div className="flex justify-between items-center border-t pt-3 text-sm">
                <span className="text-gray-600">
                  Base: {fmt(reportData.estimate.price)} +{" "}
                  {fmt(renovationData.addedValue)}{" "}
                  <span className="text-xs text-gray-400">
                    (spent {fmt(renovationData.totalSpent)})
                  </span>
                </span>
                <span className="text-base font-bold text-primary">
                  = {fmt(renovationData.adjustedValue)}
                </span>
              </div>
            </div>
          )}

          <div className="mt-8 text-xs text-gray-400 text-center border-t pt-4 hidden print:block">
            This estimate is generated by an automated valuation model (AVM)
            using public and listing data. It is not a formal appraisal. Consult
            a licensed appraiser for financing decisions. Data sourced from
            public records and listing data. Generated by Domuzz — domuzz.com —{" "}
            {new Date().toLocaleDateString()}
          </div>
        </>
      )}
    </div>
  );
}